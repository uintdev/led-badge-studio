/// Notices for the Rust libraries in the build, generated by `cargo about`
/// (see docs/building.md, "Regenerating generated files").
pub const THIRD_PARTY_NOTICES: &str = include_str!("../../../THIRD_PARTY_NOTICES.txt");

/// A library as listed in [`THIRD_PARTY_NOTICES`].
#[derive(Clone, Debug)]
pub struct CrateRef {
    pub name: String,
    pub version: String,
    pub repository: Option<String>,
    pub authors: Vec<String>,
}

/// One license section of [`THIRD_PARTY_NOTICES`]: its name, the crates that
/// use it and the full text.
#[derive(Clone, Debug)]
pub struct ThirdPartySection {
    pub name: String,
    pub used_by: Vec<CrateRef>,
    pub text: String,
}

const RULE: &str = "--------------------------------------------------------------------------------";

/// One third-party library with everything the notices say about it, merged
/// across its versions and license sections (cargo-about lists a library once
/// per distinct license text it found, so the same library can appear many
/// times). [`THIRD_PARTY_NOTICES`] keeps every text exactly as shipped.
#[derive(Clone, Debug)]
pub struct Library {
    pub name: String,
    /// Every version in the build, sorted.
    pub versions: Vec<String>,
    pub repository: Option<String>,
    /// From the library's package metadata.
    pub authors: Vec<String>,
    /// Distinct copyright notices from all of the library's license texts,
    /// including license headers in its source files.
    pub copyrights: Vec<String>,
    pub licenses: Vec<LibraryLicense>,
}

/// One license of a [`Library`].
#[derive(Clone, Debug)]
pub struct LibraryLicense {
    /// License name, e.g. "MIT License".
    pub name: String,
    /// The library's own license text without copyright lines and without
    /// source code; if it only had license headers in source files, the most
    /// common wording of that license in the build.
    pub text: String,
}

/// A license line with comment markers (`//`, `#`, ` * `…) removed.
fn uncomment(line: &str) -> &str {
    line.trim()
        .trim_start_matches("/*")
        .trim_end_matches("*/")
        .trim_start_matches(['/', '#', '*', ';', '!'])
        .trim()
}

/// A copyright notice line ("Copyright (c) 2020 Name", "© 2019 Name",
/// "(c) 2018 Name"), not license prose that happens to start with
/// "copyright …" or a list item "(c) You must …", nor a heading like
/// "COPYRIGHT AND PERMISSION NOTICE".
fn is_copyright(line: &str) -> bool {
    let l = uncomment(line);
    if let Some(rest) = l.strip_prefix("(c)").or_else(|| l.strip_prefix("(C)")) {
        return rest.trim_start().starts_with(|c: char| c.is_ascii_digit());
    }
    if l.starts_with('©') {
        return true;
    }
    let Some(rest) = l.strip_prefix("Copyright").or_else(|| l.strip_prefix("COPYRIGHT")) else {
        return false;
    };
    if !rest.starts_with([' ', ':']) {
        return false;
    }
    let heading = !l.chars().any(|c| c.is_ascii_digit()) && !l.chars().any(char::is_lowercase);
    let rest = rest.trim_start_matches([' ', ':']);
    !heading && rest.starts_with(|c: char| c == '(' || c == '©' || c.is_ascii_digit() || c.is_uppercase())
}

/// Copyright notices in `text`, one per line. A notice that ends in "by"
/// continues on the next line.
fn copyright_notices(text: &str) -> Vec<String> {
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        if !is_copyright(line) {
            continue;
        }
        let mut notice = uncomment(line).to_string();
        if notice.ends_with(" by")
            && let Some(next) = lines[i + 1..].iter().map(|l| uncomment(l)).find(|l| !l.is_empty())
        {
            notice = format!("{notice} {next}");
        }
        out.push(notice.split_whitespace().collect::<Vec<_>>().join(" "));
    }
    out
}

/// Template lines such as "Copyright [yyyy] [name of copyright owner]".
fn is_placeholder(line: &str) -> bool {
    let l = line.to_lowercase();
    [
        "[yyyy]",
        "<year>",
        "{yyyy}",
        "[name of copyright owner]",
        "<copyright holders>",
    ]
    .iter()
    .any(|p| l.contains(p))
}

/// License headers copied from source files (cargo-about picks those up
/// too) rather than a LICENSE file: keep their copyright lines, not the code.
fn looks_like_code(text: &str) -> bool {
    let code = text
        .lines()
        .map(str::trim_start)
        .filter(|l| {
            [
                "#include", "#define", "typedef ", "use ", "fn ", "pub ", "static ", "struct ", "impl ",
            ]
            .iter()
            .any(|k| l.starts_with(k))
                || *l == "}"
                || l.ends_with(");")
        })
        .count();
    code >= 3
}

/// The text without copyright lines or surrounding blank lines. Texts taken
/// from comment blocks in source files lose their comment markers.
fn without_copyrights(text: &str) -> String {
    let lines: Vec<&str> = text.lines().filter(|l| !is_copyright(l)).collect();
    let non_empty = lines.iter().filter(|l| !l.trim().is_empty()).count();
    let commented = lines
        .iter()
        .filter(|l| {
            let t = l.trim_start();
            t.starts_with("//") || t.starts_with("/*") || t.starts_with('*') || t.starts_with('#')
        })
        .count();
    let kept: Vec<&str> = if non_empty > 0 && commented * 2 > non_empty {
        lines
            .iter()
            .map(|l| uncomment(l))
            .filter(|l| !l.chars().all(|c| c == '*' || c == '/'))
            .collect()
    } else {
        lines
    };
    kept.join("\n").trim().to_string()
}

/// This project's own crates, which cargo-about lists too.
const OWN_CRATES: &[&str] = &[
    "badge-app",
    "badge-core",
    "badge-formats",
    "badge-io",
    "badge-render",
    "badgectl",
];

fn normalized(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The most common wording of each license in the build, without copyright
/// lines; used for libraries whose only texts are source-file headers.
fn common_texts(sections: &[ThirdPartySection]) -> std::collections::HashMap<String, String> {
    use std::collections::HashMap;
    let mut counts: HashMap<&str, HashMap<String, (usize, String)>> = HashMap::new();
    for sec in sections.iter().filter(|s| !looks_like_code(&s.text)) {
        let text = without_copyrights(&sec.text);
        counts
            .entry(&sec.name)
            .or_default()
            .entry(normalized(&text))
            .or_insert((0, text))
            .0 += 1;
    }
    counts
        .into_iter()
        .filter_map(|(name, texts)| {
            let (_, text) = texts
                .into_values()
                .max_by(|a, b| a.0.cmp(&b.0).then_with(|| b.1.len().cmp(&a.1.len())))?;
            Some((name.to_string(), text))
        })
        .collect()
}

/// Every third-party library once, sorted by name.
pub fn third_party_libraries() -> Vec<Library> {
    use std::collections::{BTreeMap, BTreeSet};
    struct Acc {
        lib: Library,
        versions: BTreeSet<String>,
        copyrights: BTreeSet<String>,
        // License name -> the library's own clean text, if it has one.
        licenses: Vec<(String, Option<String>)>,
    }
    let sections = third_party_sections();
    let common = common_texts(&sections);
    let mut libs: BTreeMap<String, Acc> = BTreeMap::new();
    for sec in &sections {
        let notices: Vec<String> = copyright_notices(&sec.text)
            .into_iter()
            .filter(|n| !is_placeholder(n))
            .collect();
        let own_text = (!looks_like_code(&sec.text)).then(|| without_copyrights(&sec.text));
        for c in sec.used_by.iter().filter(|c| !OWN_CRATES.contains(&c.name.as_str())) {
            let acc = libs.entry(c.name.to_lowercase()).or_insert_with(|| Acc {
                lib: Library {
                    name: c.name.clone(),
                    versions: Vec::new(),
                    repository: None,
                    authors: Vec::new(),
                    copyrights: Vec::new(),
                    licenses: Vec::new(),
                },
                versions: BTreeSet::new(),
                copyrights: BTreeSet::new(),
                licenses: Vec::new(),
            });
            acc.versions.insert(c.version.clone());
            if acc.lib.repository.is_none() {
                acc.lib.repository.clone_from(&c.repository);
            }
            for a in &c.authors {
                if !acc.lib.authors.contains(a) {
                    acc.lib.authors.push(a.clone());
                }
            }
            acc.copyrights.extend(notices.iter().cloned());
            match acc.licenses.iter_mut().find(|(name, _)| *name == sec.name) {
                Some((_, text)) if text.is_none() => text.clone_from(&own_text),
                Some(_) => {}
                None => acc.licenses.push((sec.name.clone(), own_text.clone())),
            }
        }
    }
    libs.into_values()
        .map(|acc| {
            let mut lib = acc.lib;
            lib.versions = acc.versions.into_iter().collect();
            lib.copyrights = acc.copyrights.into_iter().collect();
            lib.licenses = acc
                .licenses
                .into_iter()
                .map(|(name, text)| {
                    let text = text.or_else(|| common.get(&name).cloned()).unwrap_or_default();
                    LibraryLicense { name, text }
                })
                .collect();
            lib
        })
        .collect()
}

/// Splits [`THIRD_PARTY_NOTICES`] into its license sections, as written.
pub fn third_party_sections() -> Vec<ThirdPartySection> {
    let mut out = Vec::new();
    let mut parts = THIRD_PARTY_NOTICES.split(RULE).skip(1);
    while let (Some(name), Some(body)) = (parts.next(), parts.next()) {
        let mut used_by: Vec<CrateRef> = Vec::new();
        let mut text = String::new();
        let mut in_list = true;
        for line in body.lines() {
            if in_list {
                // "  * name version - repository"
                if let Some(c) = line.strip_prefix("  * ") {
                    let (id, repository) = match c.split_once(" - ") {
                        Some((id, repo)) => (id, Some(repo.trim().to_string())),
                        None => (c, None),
                    };
                    let (name, version) = id.trim().split_once(' ').unwrap_or((id.trim(), ""));
                    used_by.push(CrateRef {
                        name: name.to_string(),
                        version: version.to_string(),
                        repository,
                        authors: Vec::new(),
                    });
                    continue;
                }
                // "    Authors: a; b"
                if let Some(authors) = line.strip_prefix("    Authors: ") {
                    if let Some(last) = used_by.last_mut() {
                        last.authors = authors.split("; ").map(str::to_string).collect();
                    }
                    continue;
                }
                if line.starts_with("Used by:") || line.trim().is_empty() {
                    continue;
                }
                in_list = false;
            }
            text.push_str(line);
            text.push('\n');
        }
        out.push(ThirdPartySection {
            name: name.trim().to_string(),
            used_by,
            text: text.trim().to_string(),
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notices_parse_and_cover_key_crates() {
        let sections = third_party_sections();
        assert!(sections.len() > 20);
        let all: Vec<&CrateRef> = sections.iter().flat_map(|s| &s.used_by).collect();
        for krate in ["gpui-pre", "hidapi", "serialport", "image"] {
            assert!(all.iter().any(|c| c.name == krate), "{krate} missing from notices");
        }
        assert!(all.iter().all(|c| !c.version.is_empty()));
        assert!(all.iter().any(|c| !c.authors.is_empty()));
        assert!(sections.iter().all(|s| !s.text.is_empty()));
    }

    #[test]
    fn libraries_are_merged_and_clean() {
        let libs = third_party_libraries();
        let mut names: Vec<String> = libs.iter().map(|l| l.name.to_lowercase()).collect();
        let count = names.len();
        names.dedup();
        assert_eq!(names.len(), count, "a library is listed twice");
        assert!(libs.iter().all(|l| !l.name.starts_with("badge")));
        // freetype-sys appears in many license sections (the C files it
        // bundles carry license headers) but is listed once, with its
        // authors' notices.
        let freetype = libs.iter().find(|l| l.name == "freetype-sys").unwrap();
        assert_eq!(freetype.versions.len(), 1);
        assert!(freetype.copyrights.iter().any(|c| c.contains("PistonDevelopers")));
        assert!(freetype.licenses.iter().any(|l| l.name == "MIT License"));
        // Several versions of one library are merged.
        assert!(libs.iter().any(|l| l.versions.len() > 1));
        for lib in &libs {
            assert!(!lib.licenses.is_empty(), "{} has no license", lib.name);
            for lic in &lib.licenses {
                assert!(!lic.text.is_empty(), "{}: {} has no text", lib.name, lic.name);
                assert!(
                    !lic.text.contains("#include") && !lic.text.contains("typedef"),
                    "{} shows code",
                    lib.name
                );
            }
            assert!(
                lib.copyrights
                    .iter()
                    .all(|c| !c.contains("You must") && !c.contains("[yyyy]"))
            );
        }
        assert!(
            libs.iter()
                .flat_map(|l| &l.licenses)
                .all(|l| !l.text.contains("/*") && !l.text.contains("\n * "))
        );
        let apache = libs
            .iter()
            .flat_map(|l| &l.licenses)
            .find(|l| l.name == "Apache License 2.0")
            .unwrap();
        assert!(apache.text.contains("(c) You must retain"));
    }

    #[test]
    fn copyright_detection() {
        for yes in [
            "Copyright (c) 2020 Jane",
            "// Copyright 2015 Brian Smith.",
            " * © 2019 X",
            "(c) 2018 Y",
            "Copyright The Rust Project Developers",
            "COPYRIGHT 2001 FOO",
        ] {
            assert!(is_copyright(yes), "{yes}");
        }
        for no in [
            "copyright owner or by an individual",
            "(c) You must retain",
            "COPYRIGHT AND PERMISSION NOTICE",
            "Copyrights are fun",
            "The above copyright notice",
        ] {
            assert!(!is_copyright(no), "{no}");
        }
        assert_eq!(
            copyright_notices("Copyright (C) 2001 by\n  Francesco Zappa Nardelli\n"),
            vec!["Copyright (C) 2001 by Francesco Zappa Nardelli"]
        );
    }

    #[test]
    fn font_licenses_are_present() {
        assert!(FONT_LICENSES.iter().any(|d| d.text.contains("SIL OPEN FONT LICENSE")));
        assert!(FONT_LICENSES.iter().any(|d| d.text.contains("TakWolf")));
    }
}
