/// Number of built-in icons (`~0`..`~f`).
pub const ICON_COUNT: usize = 16;

/// Returns built-in icon `index` sized for a badge `height` rows tall.
/// Icons are square: 11x11, 12x12 or 16x16, stored two bytes per row.
pub fn icon(index: usize, height: usize) -> crate::Glyph {
    let (table, size): (&[u8], usize) = match height {
        0..=11 => (&ICONS_11, 11),
        12..=15 => (&ICONS_12, 12),
        _ => (&ICONS_16, 16),
    };
    let index = index % ICON_COUNT;
    let bytes = &table[index * size * 2..(index + 1) * size * 2];
    let mut pixels = vec![false; size * size];
    for y in 0..size {
        let row = u16::from_be_bytes([bytes[y * 2], bytes[y * 2 + 1]]);
        for x in 0..size {
            pixels[y * size + x] = row & (0x8000 >> x) != 0;
        }
    }
    crate::Glyph {
        width: size,
        height: size,
        left: 0,
        top: 0,
        advance: size,
        pixels,
    }
}
